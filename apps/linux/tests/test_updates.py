import re
import tempfile
import unittest
from pathlib import Path

from beamcam import updates

LINUX = Path(__file__).resolve().parent.parent


class UpdatesTest(unittest.TestCase):
    def test_asks_only_packages_that_can_add_the_repository_until_no(self):
        self.assertTrue(updates.should_ask(available=True, turned_on=False, answer=None))
        self.assertFalse(updates.should_ask(available=True, turned_on=False, answer=False))
        self.assertTrue(updates.should_ask(available=True, turned_on=False, answer=True))
        self.assertFalse(updates.should_ask(available=True, turned_on=True, answer=None))
        self.assertFalse(updates.should_ask(available=False, turned_on=False, answer=None))

    def test_any_repository_file_means_on(self):
        with tempfile.TemporaryDirectory() as folder:
            apt, dnf = Path(folder, "beamcam.sources"), Path(folder, "beamcam.repo")
            self.assertFalse(updates.turned_on((apt, dnf)))
            dnf.write_text("[beamcam]\n")
            self.assertTrue(updates.turned_on((apt, dnf)))

    def test_a_disabled_repository_is_off(self):
        with tempfile.TemporaryDirectory() as folder:
            apt, dnf = Path(folder, "beamcam.sources"), Path(folder, "beamcam.repo")
            apt.write_text("Types: deb\nURIs: https://example.org/apt/\nSuites: ./\nEnabled: no\n")
            self.assertFalse(updates.turned_on((apt, dnf)))
            dnf.write_text("[beamcam]\nenabled = 0\n")
            self.assertFalse(updates.turned_on((apt, dnf)))
            dnf.write_text("[beamcam]\nenabled=False\n")
            self.assertFalse(updates.turned_on((apt, dnf)))
            apt.write_text("Types: deb\nURIs: https://example.org/apt/\nSuites: ./\n")
            self.assertTrue(updates.turned_on((apt, dnf)))

    def test_dnf_turned_off_in_the_software_settings_is_off(self):
        with tempfile.TemporaryDirectory() as folder:
            dnf, overrides = Path(folder, "beamcam.repo"), Path(folder, "repos.override.d")
            dnf.write_text("[beamcam]\nenabled=1\n")
            overrides.mkdir()
            self.assertTrue(updates.turned_on((dnf,), overrides))
            (overrides / "99-config_manager.repo").write_text("# Generated by dnf\n[other]\nenabled = 0\n[beamcam]\nenabled = 0\n")
            self.assertFalse(updates.turned_on((dnf,), overrides))
            (overrides / "99-zz-admin.repo").write_text("[beamcam]\nenabled=1\n")
            self.assertTrue(updates.turned_on((dnf,), overrides))
            dnf.write_text("[beamcam]\nenabled=0\n")
            self.assertTrue(updates.turned_on((dnf,), overrides), "the override outranks the file")
            (overrides / "99-zz-admin.repo").write_bytes(b"[beamcam]\nname=\xff\nenabled=0\n")
            self.assertFalse(updates.turned_on((dnf,), overrides), "a broken override is skipped")

    def test_the_helper_writes_what_the_window_reads(self):
        helper = (LINUX / "data" / "updates").read_text()
        written = set(re.findall(r"^(?:APT_SOURCE|DNF_REPO)=(\S+)$", helper, re.MULTILINE))
        self.assertEqual(written, {str(path) for path in updates.SOURCES})
        self.assertIn(f"DNF_OVERRIDE={updates.DNF_OVERRIDES}/99-config_manager.repo\n", helper)
        self.assertIn('URL="${BEAMCAM_REPO_URL:-https://jannikherter.github.io/beamcam}"', helper)
        policy = (LINUX / "data" / "org.beamcam.Beamcam.policy").read_text()
        self.assertIn(f'exec.path">{updates.HELPER}<', policy)
        for message in updates.HELPER_MESSAGES:
            self.assertIn(f'echo "{message}" >&2', helper)
        install = (LINUX / "packaging" / "install-data.sh").read_text()
        self.assertIn(f'"$dest{updates.HELPER}"', install)
